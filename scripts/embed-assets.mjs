// Inlines fonts and screenshots as base64 so the SVG is self-contained.
// An SVG loaded through <img> cannot fetch anything, so every byte it shows
// has to be inside it. Re-run after changing anything in assets/.
import { readFileSync, writeFileSync } from 'node:fs';

const b64 = (p) => readFileSync(new URL(`../assets/${p}`, import.meta.url)).toString('base64');

const out = `// Generated by scripts/embed-assets.mjs. Do not edit.
export const FONT_REGULAR = '${b64('caskaydia-Regular.woff2')}';
export const FONT_BOLD = '${b64('caskaydia-Bold.woff2')}';
export const SHOT_ORBIS = '${b64('orbis.jpg')}';
export const SHOT_MELLO = '${b64('mello.jpg')}';
`;
writeFileSync(new URL('../lib/assets.generated.js', import.meta.url), out);
console.log(`lib/assets.generated.js: ${(out.length / 1024).toFixed(1)} KB`);
